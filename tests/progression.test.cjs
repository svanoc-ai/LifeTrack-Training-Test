const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const src=fs.readFileSync(require('node:path').join(__dirname,'../src/progression.ts'),'utf8');
const compiled=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const moduleExports={};vm.runInNewContext(compiled,{exports:moduleExports,require,Date,Map,Number,Math,Array});
const {progressionPoints,groupPoints}=moduleExports;
const make=(id,date,reps,rir=3,kg=40,extra=false)=>({id,startedAt:date,updatedAt:date,status:'completed',targets:[{exerciseId:'curl',sets:3,reps:10,rir:2}],exerciseResults:[{index:0,sets:[1,2,3].map((set,i)=>({set,reps:reps[i],rir,loadKg:kg,validated:true})).concat(extra?[{set:4,reps:1,rir:0,loadKg:kg,validated:true}]:[])}]});
const a=make('a','2026-10-01T08:00:00Z',[12,12,12],3,40,true);
const b=make('b','2026-10-08T08:00:00Z',[12,12,12]);
const c=make('c','2026-10-09T08:00:00Z',[9,10,10]);
const points=progressionPoints([a,b,c], 'curl');
assert.equal(points.length,3);
assert.equal(points[0].confirmed,true,'confirmation on subsequent session');
assert.equal(points[0].minReps,12,'extra set ignored');
assert.equal(points[1].confirmed,false,'no subsequent qualifying confirmation');
assert.equal(points[2].success,false,'missed reps');
assert.equal(groupPoints(points,'week').length,2,'last complete session per week');
assert.equal(groupPoints(points,'month')[0].sessionId,'c','last complete of month');
assert.equal(progressionPoints([{...a,id:'invalid',startedAt:'bad',updatedAt:'bad'}],'curl').length,0,'invalid dates skipped');
console.log('PASS: 7 regression checks');
